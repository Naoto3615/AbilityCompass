/**
 * Extracts KanjiVG stroke path data for 2nd grade kanji
 * and generates a TypeScript data file for embedding in the app.
 *
 * Run: node scripts/extract-stroke-data.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// All 2nd grade kanji from kanji2nd.ts
const KANJI_LIST = '引羽雲園遠何科夏家歌画回会海絵外角楽活間丸岩顔汽記帰牛魚強教近兄形計元言古公工広交光考高国黒今細作算思止弱首秋春書少場色食新親数星晴雪船線前多太体台地知昼長鳥朝通弟店電冬東当答同読南馬買半番父風分聞歩母北妹万明鳴毛門夜野友曜来理話行合西声切弓京原谷才市矢姉紙寺自時室社週図組走池茶直点頭道内肉売麦米方毎用里弾戸午後語黄心刀';

const kanjivgDir = path.join(__dirname, '../node_modules/@madcat/kanjivg/dist/main');
const outputDir = path.join(__dirname, '../src/data/strokeOrder');

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

/**
 * Parse SVG to extract ordered stroke paths
 * Returns array of path 'd' strings in stroke order
 */
function extractPaths(svgContent) {
  const paths = [];
  const pathRegex = /<path[^>]*id="kvg:[0-9a-f]+-s(\d+)"[^>]*d="([^"]+)"[^>]*/g;
  let match;
  while ((match = pathRegex.exec(svgContent)) !== null) {
    const strokeNum = parseInt(match[1], 10);
    paths[strokeNum - 1] = match[2];
  }
  return paths.filter(Boolean);
}

/**
 * Parse JSON to extract stroke start positions
 */
function extractStarts(jsonContent) {
  const data = JSON.parse(jsonContent);
  return data.map((s) => ({ x: s.start.x, y: s.start.y }));
}

const result = {};
const missing = [];

for (const ch of KANJI_LIST) {
  const cp = ch.codePointAt(0).toString(16).padStart(5, '0');
  const svgFile = path.join(kanjivgDir, `${cp}.svg`);
  const jsonFile = path.join(kanjivgDir, `${cp}.json`);
  
  if (fs.existsSync(svgFile)) {
    const svgContent = fs.readFileSync(svgFile, 'utf-8');
    const paths = extractPaths(svgContent);
    if (paths.length > 0) {
      const starts = fs.existsSync(jsonFile)
        ? extractStarts(fs.readFileSync(jsonFile, 'utf-8'))
        : [];
      result[ch] = { paths, starts };
    } else {
      missing.push(`${ch}(${cp}) - no paths found`);
    }
  } else {
    const cp4 = ch.codePointAt(0).toString(16).padStart(4, '0');
    const svgFile4 = path.join(kanjivgDir, `${cp4}.svg`);
    const jsonFile4 = path.join(kanjivgDir, `${cp4}.json`);
    if (fs.existsSync(svgFile4)) {
      const svgContent = fs.readFileSync(svgFile4, 'utf-8');
      const paths = extractPaths(svgContent);
      if (paths.length > 0) {
        const starts = fs.existsSync(jsonFile4)
          ? extractStarts(fs.readFileSync(jsonFile4, 'utf-8'))
          : [];
        result[ch] = { paths, starts };
      }
    } else {
      missing.push(`${ch}(${cp})`);
    }
  }
}

console.log(`Extracted stroke data for ${Object.keys(result).length} kanji`);
if (missing.length > 0) {
  console.warn(`Missing data for: ${missing.join(', ')}`);
}

// Generate TypeScript file
const tsContent = `// Auto-generated by scripts/extract-stroke-data.mjs
// KanjiVG data © Ulrich Apel, licensed under CC BY-SA 3.0
// Source: https://kanjivg.tagaini.net/

export interface StrokeData {
  /** SVG path 'd' strings in stroke order */
  paths: string[];
  /** Start coordinates for each stroke (in 0-109 viewBox space) */
  starts: { x: number; y: number }[];
}

/**
 * Stroke order data for 2nd grade kanji.
 * The viewBox for all paths is "0 0 109 109".
 */
export const strokeOrderData: Record<string, StrokeData> = ${JSON.stringify(result, null, 2)};
`;

const outputFile = path.join(outputDir, 'index.ts');
fs.writeFileSync(outputFile, tsContent, 'utf-8');
console.log(`Written to ${outputFile}`);
